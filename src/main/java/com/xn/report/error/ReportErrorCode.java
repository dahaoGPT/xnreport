package com.xn.report.error;

/**
 * 报表生成统一错误码枚举。
 * <p>
 * 涵盖配置加载/校验、SQL执行、数据集校验、规则计算、文字占位符解析、图表生成、
 * Excel/Word文档渲染及输出发布等全流程异常分类。
 * </p>
 */
public enum ReportErrorCode {

    /** 配置文件不存在或不可读。 */
    CFG_001("CFG-001"),

    /** 配置结构或 Schema 语法不合法。 */
    CFG_002("CFG-002"),

    /** 配置内部引用（数据集、SQL、规则等）不存在。 */
    CFG_003("CFG-003"),

    /** 数据集依赖关系存在循环依赖或拓扑排序失败。 */
    CFG_004("CFG-004"),

    /** SQL 外部文件读取失败。 */
    SQL_001("SQL-001"),

    /** SQL 非只读操作（包含写入关键字）或包含多条语句。 */
    SQL_002("SQL-002"),

    /** SQL 命名参数缺失或集合参数为空。 */
    SQL_003("SQL-003"),

    /** SQL 查询底层数据库执行失败。 */
    SQL_004("SQL-004"),

    /** 数据集结果形态不符合声明（如预期单行返回多行）。 */
    DATA_001("DATA-001"),

    /** 数据集缺失预期字段。 */
    DATA_002("DATA-002"),

    /** 数据集字段类型不匹配或类型转换失败。 */
    DATA_003("DATA-003"),

    /** 数据集查询返回行数超过最大限制（maxRows）。 */
    DATA_004("DATA-004"),

    /** 规则表达式或条件配置不合法。 */
    RULE_001("RULE-001"),

    /** 规则引用的字段或运行时变量无法解析。 */
    RULE_002("RULE-002"),

    /** 文本段落中的占位符无法解析。 */
    TEXT_001("TEXT-001"),

    /** 图表字段、分类或系列绑定配置不合法。 */
    CHART_001("CHART-001"),

    /** 模板中未找到对应的图表占位符或图表标记匹配失败。 */
    CHART_002("CHART-002"),

    /** 无可用的图表图片渲染器或渲染引擎异常。 */
    CHART_003("CHART-003"),

    /** Excel 模板加载或数据绑定失败。 */
    XLSX_001("XLSX-001"),

    /** Excel 输出完整性或结构校验失败。 */
    XLSX_002("XLSX-002"),

    /** Word 模板加载或数据/段落绑定失败。 */
    DOCX_001("DOCX-001"),

    /** Word 输出完整性校验失败（如遗留未替换占位符）。 */
    DOCX_002("DOCX-002"),

    /** Word 模板缺少必需的标题样式、目录域或章节锚点。 */
    DOCX_003("DOCX-003"),

    /** 输出路径非法或存在路径穿越安全风险。 */
    OUT_001("OUT-001"),

    /** 输出目标文件已存在且冲突策略为 FAIL。 */
    OUT_002("OUT-002"),

    /** 原子发布失败或工作空间清理失败。 */
    OUT_003("OUT-003");

    /** 错误码字符串标识。 */
    private final String code;

    /**
     * 构造错误码枚举项。
     *
     * @param code 错误码字符串（如 "CFG-001"）
     */
    ReportErrorCode(String code) {
        this.code = code;
    }

    /**
     * 获取错误码字符串。
     *
     * @return 错误码字符串
     */
    public String getCode() {
        return code;
    }

    @Override
    public String toString() {
        return code;
    }
}
